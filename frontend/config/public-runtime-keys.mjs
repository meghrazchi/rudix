const RUNTIME_KEY_SET = new Set(PUBLIC_RUNTIME_KEYS);

/**
 * True when `name` may be served from /runtime-config.js.
 * @param {string} name
 * @returns {boolean}
 */
export function isPublicRuntimeKey(name) {
  return RUNTIME_KEY_SET.has(name);
}

/**
 * The allowlisted values present in `env`, for /runtime-config.js. Names that
 * are not allowlisted are never copied, whatever `env` holds.
 * @param {Record<string, string | undefined>} env
 * @returns {Record<string, string>}
 */
export function pickPublicRuntimeValues(env) {
  /** @type {Record<string, string>} */
  const values = {};
  for (const name of PUBLIC_RUNTIME_KEYS) {
    const value = env[name];
    if (typeof value === "string") values[name] = value;
  }
  return values;
}

/**
 * "request" when NEXT_PUBLIC_RUNTIME_CONFIG_SOURCE is request (any case);
 * otherwise "build", the default.
 * @param {string | undefined} value
 * @returns {"build" | "request"}
 */
export function resolveRuntimeConfigSource(value) {
  return (value ?? "").trim().toLowerCase() === "request" ? "request" : "build";
}
