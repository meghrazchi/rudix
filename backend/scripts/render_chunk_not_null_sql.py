#!/usr/bin/env python3
"""Render the operator SQL that makes document_chunks.organization_id NOT NULL (R06-09).

After ``documents.chunks.backfill_tenant`` (or ``scripts/backfill_chunk_tenant.py``) has
filled every row, ``deploy/sql/document_chunks_not_null.sql``:

1. refuses to run while any row still has ``organization_id`` NULL;
2. adds ``CHECK (organization_id IS NOT NULL) NOT VALID`` (a brief lock, no scan);
3. ``VALIDATE CONSTRAINT`` (scans without blocking reads or writes);
4. ``ALTER COLUMN ... SET NOT NULL`` (PostgreSQL 12+ uses the validated check instead of a
   second scan), then drops the now redundant check;
5. enables row-level security on ``document_chunks`` with the strict tenant policy.

``deploy/sql/document_chunks_not_null_revert.sql`` undoes it. Neither is a migration: run
them by hand, without ``psql -1`` (each step must commit on its own so the validation scan
holds no exclusive lock). ``tests/test_chunk_tenant_backfill.py`` checks that the committed
files equal this output.

Usage:
    python scripts/render_chunk_not_null_sql.py           # write both files
    python scripts/render_chunk_not_null_sql.py --check   # exit 1 if a committed file differs
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

from app.db.rls import RLS_PENDING_TABLES, TENANT_RLS_POLICY_NAME, build_strict_policy_sql

DEPLOY_SQL_DIR = Path(__file__).resolve().parents[2] / "deploy" / "sql"
APPLY_FILE = "document_chunks_not_null.sql"
REVERT_FILE = "document_chunks_not_null_revert.sql"
TABLE = "document_chunks"
CONSTRAINT = "chk_chunks_org_not_null"

_HEADER = """\
-- {title}
--
-- GENERATED by backend/scripts/render_chunk_not_null_sql.py. Do not edit; re-render.
--
-- Not applied automatically and not part of any migration. Run as the migration owner,
-- WITHOUT -1 (every statement commits on its own):
--
--   psql "$DATABASE_MIGRATION_URL_PSQL" -v ON_ERROR_STOP=1 -f deploy/sql/{file}
--
{body}
-- Give up if a table lock is not granted within 5 s (re-run later); the validation scan
-- itself may take long, so it gets no statement timeout.
SET lock_timeout = '5s';
SET statement_timeout = 0;

"""

_APPLY_BODY = """\
-- Run it after documents.chunks.backfill_tenant reports nothing left (or
-- scripts/backfill_chunk_tenant.py --dry-run prints remaining=0). It stops before changing
-- anything if a row still has organization_id NULL. Afterwards set
-- KEYWORD_SEARCH_TENANT_COLUMN=on. With FORCE ROW LEVEL SECURITY applied to the other
-- tenant tables (deploy/sql/force_rls.sql), also force it here:
--   ALTER TABLE document_chunks FORCE ROW LEVEL SECURITY;
-- Rollback: deploy/sql/document_chunks_not_null_revert.sql.
"""

_REVERT_BODY = """\
-- Rollback of deploy/sql/document_chunks_not_null.sql: drops the tenant policy, disables
-- row-level security on document_chunks, and makes organization_id nullable again. Set
-- KEYWORD_SEARCH_TENANT_COLUMN=auto (or off) first.
"""


def _guard_sql() -> str:
    return (
        "DO $$\n"
        "BEGIN\n"
        f"    IF EXISTS (SELECT 1 FROM {TABLE} WHERE organization_id IS NULL) THEN\n"
        f"        RAISE EXCEPTION '{TABLE}: organization_id NULL rows remain; run the backfill';\n"
        "    END IF;\n"
        "END\n"
        "$$;\n"
    )


def _add_check_sql() -> str:
    return (
        "DO $$\n"
        "BEGIN\n"
        "    IF NOT EXISTS (\n"
        "        SELECT 1 FROM pg_constraint\n"
        f"        WHERE conname = '{CONSTRAINT}' AND conrelid = '{TABLE}'::regclass\n"
        "    ) THEN\n"
        f"        ALTER TABLE {TABLE} ADD CONSTRAINT {CONSTRAINT}\n"
        "            CHECK (organization_id IS NOT NULL) NOT VALID;\n"
        "    END IF;\n"
        "END\n"
        "$$;\n"
    )


def render_apply_sql() -> str:
    if TABLE not in RLS_PENDING_TABLES:
        raise RuntimeError(f"{TABLE} is no longer a pending RLS table")
    enable_sql, drop_policy_sql, create_policy_sql = build_strict_policy_sql(TABLE)
    statements = [
        "-- 1. Refuse while any row is not backfilled.",
        _guard_sql(),
        "-- 2. Enforce the column for new rows at once; existing rows are checked in step 3.",
        "--    Skipped when a previous run already added the check (rerun-safe).",
        _add_check_sql(),
        "-- 3. Scan existing rows (SHARE UPDATE EXCLUSIVE: reads and writes continue).",
        f"ALTER TABLE {TABLE} VALIDATE CONSTRAINT {CONSTRAINT};",
        "",
        "-- 4. NOT NULL uses the validated check (no second scan); the check is then redundant.",
        f"ALTER TABLE {TABLE} ALTER COLUMN organization_id SET NOT NULL;",
        f"ALTER TABLE {TABLE} DROP CONSTRAINT IF EXISTS {CONSTRAINT};",
        "",
        "-- 5. Strict tenant policy (the same condition as every RLS_STRICT_TABLES table).",
        "BEGIN;",
        f"{enable_sql};",
        f"{drop_policy_sql};",
        f"{create_policy_sql};",
        "COMMIT;",
    ]
    body = "\n".join(statements) + "\n"
    return (
        _HEADER.format(
            title="Rudix: document_chunks.organization_id NOT NULL and tenant policy (0.6.0).",
            file=APPLY_FILE,
            body=_APPLY_BODY,
        )
        + body
    )


def render_revert_sql() -> str:
    statements = [
        "BEGIN;",
        f"DROP POLICY IF EXISTS {TENANT_RLS_POLICY_NAME} ON {TABLE};",
        f"ALTER TABLE {TABLE} NO FORCE ROW LEVEL SECURITY;",
        f"ALTER TABLE {TABLE} DISABLE ROW LEVEL SECURITY;",
        "COMMIT;",
        "",
        f"ALTER TABLE {TABLE} ALTER COLUMN organization_id DROP NOT NULL;",
        f"ALTER TABLE {TABLE} DROP CONSTRAINT IF EXISTS {CONSTRAINT};",
    ]
    body = "\n".join(statements) + "\n"
    return (
        _HEADER.format(
            title="Rudix: revert document_chunks NOT NULL and tenant policy (0.6.0).",
            file=REVERT_FILE,
            body=_REVERT_BODY,
        )
        + body
    )


def rendered_files() -> dict[str, str]:
    return {APPLY_FILE: render_apply_sql(), REVERT_FILE: render_revert_sql()}


def main(argv: Sequence[str] | None = None, *, directory: Path = DEPLOY_SQL_DIR) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a committed file differs")
    args = parser.parse_args(argv)
    stale: list[str] = []
    for name, content in rendered_files().items():
        path = directory / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")
    if stale:
        print(
            f"stale: {', '.join(stale)}; run scripts/render_chunk_not_null_sql.py",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
