#!/usr/bin/env python3
"""Render the operator SQL that turns ``FORCE ROW LEVEL SECURITY`` on or off (0.5.0, S3).

``FORCE`` makes the tenant policies apply to the table owner too. It only changes
deployments that still connect as the owner, so it ships as operator SQL, not as a
migration: apply ``deploy/sql/force_rls.sql`` after the role split (``DATABASE_URL`` on
``rudix_app``) and the soft-denial week, then set ``RLS_ENFORCEMENT=strict``. Roll back with
``deploy/sql/unforce_rls.sql``.

The table list comes from ``app.db.rls`` (``RLS_STRICT_TABLES`` and ``RLS_LOOKUP_TABLES``);
identity tables have no policy and are left alone. ``tests/test_force_rls_sql.py`` checks
that the committed files equal this output.

Usage:
    python scripts/render_force_rls_sql.py           # write both files
    python scripts/render_force_rls_sql.py --check   # exit 1 if a committed file differs
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

from app.db.rls import RLS_LOOKUP_TABLES, RLS_STRICT_TABLES, _validate_identifier

DEPLOY_SQL_DIR = Path(__file__).resolve().parents[2] / "deploy" / "sql"
FORCE_FILE = "force_rls.sql"
UNFORCE_FILE = "unforce_rls.sql"

_HEADER = """\
-- {title}
--
-- GENERATED by backend/scripts/render_force_rls_sql.py from app.db.rls
-- (RLS_STRICT_TABLES and RLS_LOOKUP_TABLES). Do not edit; re-render after the lists change.
--
-- Not applied automatically. Run as the migration owner, in one transaction:
--
--   psql "$DATABASE_MIGRATION_URL_PSQL" -1 -v ON_ERROR_STOP=1 -f deploy/sql/{file}
--
{body}
"""

_FORCE_BODY = """\
-- Apply it only after DATABASE_URL points at rudix_app (deploy/sql/provision_roles.sql) and
-- the soft-denial week is clean; then set RLS_ENFORCEMENT=strict. With FORCE, the policies
-- apply to the table owner as well, so a service that still connects as the owner sees only
-- its bound tenant (and, under strict, nothing without one). BYPASSRLS roles
-- (rudix_maintenance) are not affected. Rollback: deploy/sql/unforce_rls.sql.
-- Each statement takes a short ACCESS EXCLUSIVE lock on its table; no data is rewritten.
"""

_UNFORCE_BODY = """\
-- Rollback of deploy/sql/force_rls.sql: the policies stop applying to the table owner again.
-- Row-level security stays enabled and the policies stay in place; set RLS_ENFORCEMENT=soft
-- first when you roll back because of denials.
"""


def forced_tables() -> list[str]:
    """Every table with a tenant policy, sorted, each identifier validated."""
    return sorted({_validate_identifier(name) for name in (*RLS_STRICT_TABLES, *RLS_LOOKUP_TABLES)})


# ``psql -1`` holds every table lock until the commit; a lock that waits behind a long query
# would queue all traffic on the tables already locked. Fail fast instead, then re-run.
_LOCK_TIMEOUT = """\
-- Give up (and roll back everything) if a table lock is not granted within 5 s; re-run later.
SET LOCAL lock_timeout = '5s';

"""


def _render(*, title: str, file: str, body: str, clause: str) -> str:
    statements = "\n".join(f"ALTER TABLE {table} {clause};" for table in forced_tables())
    return _HEADER.format(title=title, file=file, body=body) + _LOCK_TIMEOUT + statements + "\n"


def render_force_sql() -> str:
    return _render(
        title="Rudix: FORCE ROW LEVEL SECURITY on every tenant-policy table (0.5.0).",
        file=FORCE_FILE,
        body=_FORCE_BODY,
        clause="FORCE ROW LEVEL SECURITY",
    )


def render_unforce_sql() -> str:
    return _render(
        title="Rudix: NO FORCE ROW LEVEL SECURITY (rollback of force_rls.sql, 0.5.0).",
        file=UNFORCE_FILE,
        body=_UNFORCE_BODY,
        clause="NO FORCE ROW LEVEL SECURITY",
    )


def rendered_files() -> dict[str, str]:
    return {FORCE_FILE: render_force_sql(), UNFORCE_FILE: render_unforce_sql()}


def main(argv: Sequence[str] | None = None, *, directory: Path = DEPLOY_SQL_DIR) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a committed file differs")
    args = parser.parse_args(argv)
    stale: list[str] = []
    for name, content in rendered_files().items():
        path = directory / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")
    if stale:
        print(f"stale: {', '.join(stale)}; run scripts/render_force_rls_sql.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
