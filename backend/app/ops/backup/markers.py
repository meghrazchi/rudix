"""Backup markers: ``<prefix>/<kind>/latest.json`` in the backup bucket (contract 5.2.9).

A marker records the last successful backup of one kind:

.. code-block:: json

    {"kind": "postgres", "completed_at": "2026-11-28T03:15:02Z",
     "object_key": "rudix/postgres/20261128T031500Z/postgres.dump.rbk",
     "size_bytes": 1234, "sha256": "<hex of the ciphertext>", "format_version": 1}

It never holds a secret, a key id, a source hostname, a URL, or a local path. Readers
ignore unknown fields so an operator-written ``neo4j`` marker may carry more; writers emit
only the fields above.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Any, Final

from app.ops.backup.crypto import FORMAT_VERSION

MARKER_NAME: Final[str] = "latest.json"
MARKER_FIELDS: Final[tuple[str, ...]] = (
    "kind",
    "completed_at",
    "object_key",
    "size_bytes",
    "sha256",
    "format_version",
)
_KIND_RE = re.compile(r"^[a-z][a-z0-9_]{1,31}$")
_SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
# Object keys are generated by the runner; anything that looks like a URL, an absolute path,
# or a parent reference is rejected so a marker can never point outside the prefix.
_OBJECT_KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]{0,1023}$")


class MarkerError(ValueError):
    """A marker is missing a field, has a wrong type, or points outside its prefix."""


def marker_key(prefix: str, kind: str) -> str:
    _check_kind(kind)
    return f"{prefix.strip('/')}/{kind}/{MARKER_NAME}"


def kind_prefix(prefix: str, kind: str) -> str:
    _check_kind(kind)
    return f"{prefix.strip('/')}/{kind}/"


def run_stamp(moment: datetime) -> str:
    """Folder name of one backup run, e.g. ``20261128T031500Z``."""
    return moment.astimezone(UTC).strftime("%Y%m%dT%H%M%SZ")


def _check_kind(kind: str) -> None:
    if not _KIND_RE.match(kind):
        raise MarkerError("invalid backup kind")


def _format_time(moment: datetime) -> str:
    if moment.tzinfo is None:
        raise MarkerError("completed_at must be timezone-aware")
    return moment.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _parse_time(value: Any) -> datetime:
    if not isinstance(value, str):
        raise MarkerError("completed_at must be a string")
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise MarkerError("completed_at is not an ISO 8601 time") from exc
    if parsed.tzinfo is None:
        raise MarkerError("completed_at must carry a timezone")
    return parsed.astimezone(UTC)


@dataclass(frozen=True, slots=True)
class BackupMarker:
    kind: str
    completed_at: datetime
    object_key: str
    size_bytes: int
    sha256: str
    format_version: int = FORMAT_VERSION

    def validate(self, prefix: str | None = None) -> None:
        _check_kind(self.kind)
        _format_time(self.completed_at)
        key = self.object_key
        if not _OBJECT_KEY_RE.match(key) or "//" in key or ".." in key.split("/"):
            raise MarkerError("object_key is not a relative bucket key")
        if prefix is not None and not key.startswith(kind_prefix(prefix, self.kind)):
            raise MarkerError("object_key is outside the kind's prefix")
        if isinstance(self.size_bytes, bool) or not isinstance(self.size_bytes, int):
            raise MarkerError("size_bytes must be an integer")
        if self.size_bytes < 0:
            raise MarkerError("size_bytes must not be negative")
        if not _SHA256_RE.match(self.sha256):
            raise MarkerError("sha256 must be 64 lowercase hex characters")
        if isinstance(self.format_version, bool) or not isinstance(self.format_version, int):
            raise MarkerError("format_version must be an integer")
        if self.format_version < 1:
            raise MarkerError("format_version must be positive")

    def to_dict(self) -> dict[str, Any]:
        self.validate()
        return {
            "kind": self.kind,
            "completed_at": _format_time(self.completed_at),
            "object_key": self.object_key,
            "size_bytes": self.size_bytes,
            "sha256": self.sha256,
            "format_version": self.format_version,
        }

    def to_json(self) -> bytes:
        return json.dumps(self.to_dict(), sort_keys=True).encode("utf-8")

    @classmethod
    def from_dict(cls, data: Any, *, prefix: str | None = None) -> BackupMarker:
        if not isinstance(data, dict):
            raise MarkerError("marker must be a JSON object")
        missing = [name for name in MARKER_FIELDS if name not in data]
        if missing:
            raise MarkerError(f"marker is missing {', '.join(missing)}")
        for name in ("kind", "object_key", "sha256"):
            if not isinstance(data[name], str):
                raise MarkerError(f"{name} must be a string")
        marker = cls(
            kind=data["kind"],
            completed_at=_parse_time(data["completed_at"]),
            object_key=data["object_key"],
            size_bytes=data["size_bytes"],
            sha256=data["sha256"],
            format_version=data["format_version"],
        )
        marker.validate(prefix)
        return marker

    @classmethod
    def from_json(cls, raw: bytes, *, prefix: str | None = None) -> BackupMarker:
        try:
            data = json.loads(raw)
        except (ValueError, UnicodeDecodeError) as exc:
            raise MarkerError("marker is not valid JSON") from exc
        return cls.from_dict(data, prefix=prefix)
